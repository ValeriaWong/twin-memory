"""Config for Twin Memory. Environment variables only — never baked-in keys.

Reads .env if present (simple KEY=VALUE parsing, no dependency). Refuses
to run in live mode without an API key, and refuses any value that looks
like a placeholder that was never replaced.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path


@dataclass(frozen=True)
class Config:
    mode: str  # "mock" | "live"
    meko_mcp_url: str
    meko_datapack_id: str
    meko_api_key: str
    llm_provider: str
    llm_model: str
    llm_api_key: str

    @property
    def live(self) -> bool:
        return self.mode == "live"


def _load_dotenv() -> None:
    env_path = Path(__file__).resolve().parent.parent / ".env"
    if not env_path.exists():
        return
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        os.environ.setdefault(key.strip(), value.strip())


def load_config() -> Config:
    _load_dotenv()
    mode = os.environ.get("MEKO_MODE", "mock").strip().lower()
    if mode not in ("mock", "live"):
        raise ValueError(f"MEKO_MODE must be 'mock' or 'live', got {mode!r}")
    cfg = Config(
        mode=mode,
        meko_mcp_url=os.environ.get(
            "MEKO_MCP_URL", "https://mcp.mekodata.ai/mcp"
        ).strip(),
        meko_datapack_id=os.environ.get("MEKO_DATAPACK_ID", "twin-memory").strip(),
        meko_api_key=os.environ.get("MEKO_API_KEY", "").strip(),
        llm_provider=os.environ.get("LLM_PROVIDER", "mock").strip().lower(),
        llm_model=os.environ.get("LLM_MODEL", "").strip(),
        llm_api_key=os.environ.get("LLM_API_KEY", "").strip(),
    )
    if cfg.live and not cfg.meko_api_key:
        raise ValueError(
            "MEKO_MODE=live needs MEKO_API_KEY in .env (generated by Allen "
            "in Meko Settings > API Keys). Run in mock mode instead, or "
            "create the key first — never paste a key into source code."
        )
    return cfg
